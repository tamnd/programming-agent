// Tree is the generated build tree of one implementation (spec 08.5).
type Tree struct {
	Dir string
	// Test are the commands that build the implementation and run its native tests. They run in Dir.
	Test [][]string
	// Sources maps each copied file, relative to Dir, to its path in the content repository.
	Sources map[string]string
}

// Gen writes the build tree of one implementation to dir: a copy of the files with the tests, and the build files of the language. It never writes to the content tree.
func (r *Runner) Gen(dir string, n *node.Node, im node.Impl) (Tree, error) {
	t := Tree{Dir: dir, Sources: map[string]string{}}
	rc, ok := Recipes[im.Lang]
	if !ok {
		return t, fmt.Errorf("no recipe for the language %s", im.Lang)
	}
	if err := stage(dir, im, true); err != nil {
		return t, err
	}
	for _, f := range im.Files {
		t.Sources[f.Name] = f.Path
	}
	g := *r
	g.Generate = true
	cmds, err := rc.Run(&g, dir, n, im)
	if err != nil {
		return t, err
	}
	t.Test = cmds
	return t, nil
}

// Adapter is the generated adapter of one implementation for one problem (spec 09.2).
type Adapter struct {
	Dir   string
	Build [][]string
	Run   []string
	// Types are the types of T that the adapter has.
	Types []string
}

// GenAdapter writes the adapter of the contract k for one implementation to dir. It does not build it. A language without generics gets the int variant only. `prog test` also drops T = string when the entry does not build with it.
func (r *Runner) GenAdapter(dir string, n *node.Node, im node.Impl, k *contract.Contract) (Adapter, error) {
	a := Adapter{Dir: dir}
	gen, ok := adapters[im.Lang]
	if !ok {
		return a, fmt.Errorf("no adapter for the language %s", im.Lang)
	}
	if err := stage(dir, im, false); err != nil {
		return a, err
	}
	types := k.Types()
	j := &adapterJob{r: r, Dir: dir, Node: n, Impl: im, K: k, Variants: variants(k, types), First: true}
	err := gen(j)
	if errors.Is(err, errNoGenerics) {
		types = []string{"int"}
		j = &adapterJob{r: r, Dir: dir, Node: n, Impl: im, K: k, Variants: variants(k, types)}
		err = gen(j)
	}
	if err != nil {
		return a, err
	}
	a.Build, a.Run, a.Types = j.Build, j.Run, types
	return a, nil
}

// Rewrite changes the paths of the tree in a compiler error or a test failure to the paths in the content repository, so that the author sees nodes/.../merge_sort.rs:14 (spec 08.5).
func (t Tree) Rewrite(s string) string {
	dirs := []string{t.Dir}
	if real, err := filepath.EvalSymlinks(t.Dir); err == nil && real != t.Dir {
		dirs = append(dirs, real)
	}
	// A tool can print a path with a slash also on Windows, so both separators are cut.
	for _, d := range dirs {
		s = strings.ReplaceAll(s, d+string(filepath.Separator), "")
		s = strings.ReplaceAll(s, filepath.ToSlash(d)+"/", "")
	}
	names := make([]string, 0, len(t.Sources))
	for g := range t.Sources {
		names = append(names, g)
	}
	// A longer name goes first, so that test_merge_sort.py is not changed as merge_sort.py.
	sort.Slice(names, func(i, j int) bool { return len(names[i]) > len(names[j]) })
	for _, g := range names {
		re := regexp.MustCompile(`(^|[^A-Za-z0-9_./-])` + regexp.QuoteMeta(g) + `($|[^A-Za-z0-9_/-])`)
		s = re.ReplaceAllString(s, "${1}"+t.Sources[g]+"${2}")
	}
	return s
}

// WriteScript writes a POSIX shell script that runs the commands in order, so that a runner image can run a tree without prog.
func WriteScript(path string, cmds [][]string) error {
	var b strings.Builder
	b.WriteString("#!/bin/sh\n# Generated by prog gen. Do not edit.\nset -eu\ncd \"$(dirname \"$0\")\"\n")
	for _, c := range cmds {
		q := make([]string, len(c))
		for i, a := range c {
			q[i] = shellQuote(a)
		}
		b.WriteString(strings.Join(q, " ") + "\n")
	}
	return os.WriteFile(path, []byte(b.String()), 0o755)
}

var plainArg = regexp.MustCompile(`^[A-Za-z0-9_./:=,+@%-]+$`)

func shellQuote(s string) string {
	if plainArg.MatchString(s) {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
